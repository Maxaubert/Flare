// Writes crates/flare-theme/src/presets_data.rs from the oracle's presets.json and retired.json, so no value is ever typed by hand.
// Usage: node --no-warnings gen_rust.mjs <fixtures folder> <path of presets_data.rs>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [fixtures, target] = process.argv.slice(2)
if (!fixtures || !target) throw new Error('usage: node gen_rust.mjs <fixtures folder> <presets_data.rs>')
const presets = JSON.parse(readFileSync(join(fixtures, 'presets.json'), 'utf8'))
const retired = JSON.parse(readFileSync(join(fixtures, 'retired.json'), 'utf8'))
const ORDER = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white', 'brightBlack', 'brightRed', 'brightGreen', 'brightYellow', 'brightBlue', 'brightMagenta', 'brightCyan', 'brightWhite']
const q = (s) => JSON.stringify(s)
let rs = '//! GENERATED by tools/oracle/gen_rust.mjs from Prism Terminal v0.55.6 core/renderer/lib/termTheme.ts (TERM_PRESETS)\n'
rs += '//! and termThemeRetired.ts (RETIRED_THEMES). Do not edit by hand: change the oracle and regenerate.\n'
rs += '//! The sixteen of a curated preset are in ANSI order: black .. white, then brightBlack .. brightWhite.\n\n'
rs += 'use crate::preset::Preset;\n\n'
rs += `pub const PRESETS: [Preset; ${presets.length}] = [\n`
for (const p of presets) {
  const accent = p.accent ? `Some(${q(p.accent)})` : 'None'
  const ansi = p.ansi ? `Some([${ORDER.map((k) => q(p.ansi[k])).join(', ')}])` : 'None'
  rs += `    Preset { id: ${q(p.id)}, name: ${q(p.name)}, bg: ${q(p.bg)}, fg: ${q(p.fg)}, cursor: ${q(p.cursor)}, accent: ${accent}, ansi: ${ansi} },\n`
}
rs += '];\n\n'
const pairs = Object.entries(retired)
rs += `/// Retired theme ids and the kept theme their wearers go to (read wherever a theme id is read).\n`
rs += `pub const RETIRED: [(&str, &str); ${pairs.length}] = [\n`
for (const [from, to] of pairs) rs += `    (${q(from)}, ${q(to)}),\n`
rs += '];\n'
writeFileSync(target, rs)
console.log('wrote', presets.length, 'presets and', pairs.length, 'retired ids to', target)

// The fifteen terminal faces, next to the presets: crates/flare-theme/src/fonts_data.rs
const fonts = JSON.parse(readFileSync(join(fixtures, 'fonts.json'), 'utf8'))
let fs2 = '//! GENERATED by tools/oracle/gen_rust.mjs from Prism Terminal v0.55.6 core/renderer/lib/termLook.ts (TERM_FONTS).\n'
fs2 += '//! Do not edit by hand: change the oracle and regenerate.\n\n'
fs2 += 'use crate::fonts::TermFont;\n\n'
fs2 += `pub const TERM_FONTS: [TermFont; ${fonts.length}] = [\n`
for (const f of fonts) fs2 += `    TermFont { id: ${q(f.id)}, name: ${q(f.name)}, stack: ${q(f.stack)} },\n`
fs2 += '];\n'
writeFileSync(target.replace(/presets_data\.rs$/, 'fonts_data.rs'), fs2)
console.log('wrote', fonts.length, 'fonts')
