//! Regenerates the emulator's gRPC client code for flare-emu-host from the vendored proto.
//!
//! Reads `crates/flare-emu-host/proto/emulator_controller.proto`, compiles it with protox (pure Rust, no protoc),
//! generates the prost messages and the tonic client (no server), and writes
//! `crates/flare-emu-host/src/gen/android.emulation.control.rs` with a header that holds the proto's SHA-256 (line
//! endings as LF). A test in flare-emu-host checks that hash, so a changed proto without new code fails CI.

use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let host = root.join("crates/flare-emu-host");
    let proto_dir = host.join("proto");
    let proto = proto_dir.join("emulator_controller.proto");
    let out = host.join("src/gen");
    let text = std::fs::read_to_string(&proto).expect("the vendored proto");
    let hash = hex(&Sha256::digest(text.replace('\r', "").as_bytes()));

    let fds = protox::compile([&proto], [&proto_dir]).expect("the proto compiles");
    let tmp: PathBuf = std::env::temp_dir().join(format!("emu-proto-gen-{}", std::process::id()));
    std::fs::create_dir_all(&tmp).expect("a temp folder");
    tonic_prost_build::configure()
        .build_server(false)
        .build_client(true)
        .build_transport(false)
        .out_dir(&tmp)
        .compile_fds(fds)
        .expect("the code generates");

    let name = "android.emulation.control.rs";
    let code = std::fs::read_to_string(tmp.join(name)).expect("the generated file");
    let header = format!(
        "// @generated by tools/emu-proto-gen from crates/flare-emu-host/proto/emulator_controller.proto.\n\
         // Do not edit; run `cargo run --manifest-path tools/emu-proto-gen/Cargo.toml` after the proto changes.\n\
         // proto-sha256: {hash}\n"
    );
    std::fs::create_dir_all(&out).expect("the gen folder");
    std::fs::write(out.join(name), format!("{header}{code}")).expect("the generated file is written");
    let _ = std::fs::remove_dir_all(&tmp);
    println!("wrote {} (proto-sha256 {hash})", out.join(name).display());
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}
