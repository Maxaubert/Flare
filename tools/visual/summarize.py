"""Judges the start-up pictures, makes the sheets and writes the numbers of the visual tour (audit 2026-10-20).

    python tools/visual/summarize.py [--root docs/screenshots/visual]

Reads `<root>/<surface>/<pct>-<gpu|software>/` (Flare) and `<root>/pt/<surface>/<pct>-pt/` (PT),
each with `frames/*.png` and `numbers.json`. It writes
  - `sheet.png` in every cell folder (sheet.py),
  - `<root>/<surface>/compare-<pct>.png`: Flare's cells and PT's stacked, per scaling,
  - `<root>/numbers.md`: the tables the README quotes.
The start-up pictures of both sides are judged HERE, from the PNG files, with one definition: the final picture
is the last one kept; a frame is blank when it is one colour; "off brightness" is a mean more than 60 grey levels
from the final one; the bar and foot colours are the pixels at the middle of the top edge (row 3) and the bottom
edge (4 px up), compared with the final picture's.
Only the pictures the screen can show are judged (audit V1): the tour names a copy of a window that was not
shown, or was cloaked, `-hidden`, and a copy where PrintWindow painted the classic frame on a frameless window
`-copyframe` (the window manager's facts are in `numbers.json`). They are counted in their own columns and left
out of the others. PT's copies carry no tag: Playwright attaches after its window is up.
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))


def judge(frames_dir):
    files = sorted(glob.glob(os.path.join(frames_dir, "*.png")))
    if not files:
        return None
    hidden = sum(f.endswith("-hidden.png") for f in files)
    copier = sum(f.endswith("-copyframe.png") for f in files)
    files = [f for f in files if not f.endswith(("-hidden.png", "-copyframe.png"))]
    if not files:
        return None
    rows = []
    for f in files:
        a = np.asarray(Image.open(f).convert("RGB"))
        h, w, _ = a.shape
        flat = a.reshape(-1, 3)
        t = int(re.search(r"-t(\d+)ms", f).group(1)) if re.search(r"-t(\d+)ms", f) else 0
        rows.append(
            dict(
                t=t,
                size=(w, h),
                blank=bool((flat == flat[0]).all()),
                mean=float(flat.mean()),
                bar=a[3, w // 2].astype(int).tolist(),
                foot=a[max(h - 4, 0), w // 2].astype(int).tolist(),
            )
        )
    last = rows[-1]
    far = lambda p, q: any(abs(x - y) > 6 for x, y in zip(p, q))
    live = [r for r in rows if not r["blank"]]
    return dict(
        pictures=len(rows),
        hidden=hidden,
        copier=copier,
        first_ms=rows[0]["t"],
        first_nonblank_ms=live[0]["t"] if live else None,
        last_change_ms=last["t"],
        blank=sum(r["blank"] for r in rows),
        wrong_size=sum(r["size"] != last["size"] for r in rows),
        off_brightness=sum((abs(r["mean"] - last["mean"]) > 60) and not r["blank"] for r in rows),
        wrong_bar=sum(far(r["bar"], last["bar"]) and not r["blank"] for r in rows),
        wrong_foot=sum(far(r["foot"], last["foot"]) and not r["blank"] for r in rows),
        first_size=rows[0]["size"],
        final_size=last["size"],
    )


def load(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def cells(root, surface):
    """(label, folder) pairs, Flare first then PT."""
    out = []
    for d in sorted(glob.glob(os.path.join(root, surface, "*-*"))):
        out.append(("flare " + os.path.basename(d), d))
    for d in sorted(glob.glob(os.path.join(root, "pt", surface, "*-pt"))):
        out.append(("pt " + os.path.basename(d), d))
    return [c for c in out if os.path.isdir(os.path.join(c[1], "frames"))]


def sheet(folders, out, cols=5, width=440):
    subprocess.run(
        [sys.executable, os.path.join(HERE, "sheet.py"), *folders, "--out", out, "--cols", str(cols), "--width", str(width)],
        check=False,
        stdout=subprocess.DEVNULL,
    )


def pct_of(label):
    m = re.search(r"(\d+)-", label)
    return int(m.group(1)) if m else 0


def f1(v, nd=1):
    return "-" if v is None else f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.join(HERE, "..", "..", "docs", "screenshots", "visual"))
    ap.add_argument("--no-sheets", action="store_true")
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    md = ["# Numbers of the visual tour (generated by tools/visual/summarize.py)", ""]

    # -- sheets
    if not a.no_sheets:
        for surface in ["startup", "resume", "sidebar", "general", "dictation"]:
            cs = cells(root, surface)
            for _, d in cs:
                sheet([d], os.path.join(d, "sheet.png"), cols=5, width=440)
            for pct in sorted({pct_of(l) for l, _ in cs}):
                group = [d for l, d in cs if pct_of(l) == pct]
                if len(group) > 1:
                    sheet(group, os.path.join(root, surface, f"compare-{pct}.png"), cols=10 if surface == "sidebar" else 6, width=300)

    # -- sidebar
    md += ["## Sidebar slide (the slot width, css px; median of three; 240 ms ease-out declared)", ""]
    md += ["| cell | dir | frames | longest gap ms | t50 / t90 / t99 ms | settle ms | curve error (best fit) | input to first frame ms |", "|---|---|---|---|---|---|---|---|"]
    for label, d in cells(root, "sidebar"):
        n = load(os.path.join(d, "numbers.json"))
        if not n:
            continue
        for k in ("collapse", "expand"):
            runs = [r["slot"] for r in n[k] if r.get("slot")]
            if not runs:
                continue
            med = lambda key: float(np.median([r[key] for r in runs if r.get(key) is not None]))
            md.append(
                f"| {label} | {k} | {med('frames'):.0f} | {med('longest_gap_ms'):.1f} | "
                f"{med('t50_ms'):.0f} / {med('t90_ms'):.0f} / {med('t99_ms'):.0f} | {med('settle_ms'):.0f} | {med('dev_best'):.3f} | {med('input_ms'):.1f} |"
            )
    md.append("")

    # -- start-up and resume
    for surface in ("startup", "resume"):
        md += [f"## {surface}: the pictures (judged from the PNG files; only what the screen can show)", ""]
        md += ["| cell | not shown | copier frame | pictures on screen | first on screen ms | first non-blank ms | last change ms | blank | wrong size | off brightness | wrong bar | wrong foot | first size | final size |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for label, d in cells(root, surface):
            j = judge(os.path.join(d, "frames"))
            if j:
                md.append(
                    f"| {label} | {j['hidden']} | {j['copier']} | {j['pictures']} | {j['first_ms']} | {j['first_nonblank_ms']} | {j['last_change_ms']} | {j['blank']} | {j['wrong_size']} | "
                    f"{j['off_brightness']} | {j['wrong_bar']} | {j['wrong_foot']} | {j['first_size'][0]}x{j['first_size'][1]} | {j['final_size'][0]}x{j['final_size'][1]} |"
                )
        md.append("")
    md += ["## Time to first frame and to the session (ms from process start; median of the timed launches)", ""]
    md += ["| run | first frame / paint | tabs there | prompt shown |", "|---|---|---|---|"]
    newest = lambda pat: sorted(glob.glob(pat), key=os.path.getmtime)[-1:]
    for f in newest(os.path.join(root, "timings-flare-*.json")) + newest(os.path.join(root, "pt", "timings-pt-*.json")):
        t = load(f) or {}
        who = "pt" if os.sep + "pt" + os.sep in f else "flare"
        for name, v in t.items():
            m = v.get("median", {})
            if who == "pt":
                md.append(f"| {name} | {f1(m.get('fcp_since_process_ms'))} | {f1(m.get('tabs_since_process_ms'))} | {f1(m.get('prompt_since_process_ms'))} |")
            else:
                md.append(f"| flare {name} | {f1(m.get('first_frame'))} | {f1(m.get('tabs_ms'))} (wall, from CreateProcess) | {f1(m.get('prompt_wall_ms'))} (wall) |")
    md.append("")
    with open(os.path.join(root, "numbers.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    print(os.path.join(root, "numbers.md"))


if __name__ == "__main__":
    main()
