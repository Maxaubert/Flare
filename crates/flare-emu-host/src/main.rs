//! flare-emu-host: Flare's helper for Android devices in the device panel (Android plan PR A2). The only process that
//! talks to the Android emulator (gRPC, with the emulator's token, rule 1362) and to adb; one per Flare, started
//! guarded so it dies with Flare (macOS: `flare_proc::guard`; Windows: a kill-on-close job, `flare_proc::job`).
//!
//! Modes:
//! - `[--log <file>] [--restarted]`: serve Flare. Control comes as JSON lines on stdin (`flare_device::wire::Control`),
//!   answers, events and frame records go as JSON lines on stdout (`HostLine`, a `hello` first, `host: "emu"`). The
//!   frames themselves go into the region Flare made (rule 1363). The log is `<profile>/logs/emu-host.log`.
//! - `--self-test`: Flare's own parts (the generated protos, the boot command line, the hidden token), and what this
//!   machine has (SDK, emulator version, hypervisor). JSON out; exit 0 when Flare's own parts pass.
//! - `--bench <avd> <seconds> [--boot] [--width <px>] [--rotate] [--snapshots <n>]`: the frame path against a real
//!   emulator, by hand; JSON out.
//!
//! Nothing it does shows a window (rule 1370): the emulator runs with `-no-window`, and every program it runs starts
//! with no console window on Windows.

mod adb;
mod bench;
mod grpc;
mod host;
mod log;
mod run;
mod selftest;

/// The emulator's gRPC API, generated by tools/emu-proto-gen from `proto/emulator_controller.proto` (Apache-2.0).
#[allow(
    clippy::all,
    clippy::pedantic,
    clippy::undocumented_unsafe_blocks,
    missing_docs,
    unused_qualifications,
    dead_code
)]
pub mod pb {
    include!("gen/android.emulation.control.rs");
}

fn main() {
    std::process::exit(run_main());
}

fn run_main() -> i32 {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let flag = |name: &str| args.iter().any(|a| a == name);
    let value = |name: &str| {
        args.iter()
            .position(|a| a == name)
            .and_then(|i| args.get(i + 1))
            .cloned()
    };
    if flag("--self-test") {
        let (out, ok) = selftest::run();
        println!("{}", serde_json::to_string_pretty(&out).unwrap_or_default());
        return if ok { 0 } else { 1 };
    }
    if let Some(i) = args.iter().position(|a| a == "--bench") {
        let (Some(avd), Some(seconds)) = (
            args.get(i + 1).cloned(),
            args.get(i + 2).and_then(|s| s.parse::<f64>().ok()),
        ) else {
            eprintln!(
                "usage: flare-emu-host --bench <avd> <seconds> [--boot] [--width <px>] [--rotate] [--snapshots <n>]"
            );
            return 2;
        };
        let a = bench::Args {
            avd,
            seconds: seconds.clamp(1.0, 600.0),
            boot: flag("--boot"),
            width: value("--width").and_then(|v| v.parse().ok()).unwrap_or(0),
            rotate: flag("--rotate"),
            snapshots: value("--snapshots")
                .and_then(|v| v.parse().ok())
                .unwrap_or(5),
            emulator_log: value("--emulator-log").map(std::path::PathBuf::from),
        };
        return match bench::run(&a) {
            Ok(r) => {
                println!("{}", serde_json::to_string_pretty(&r).unwrap_or_default());
                0
            }
            Err(e) => {
                eprintln!("flare-emu-host: bench: {e}");
                1
            }
        };
    }
    let log = log::Log::open(value("--log").map(std::path::PathBuf::from));
    host::serve(log, flag("--restarted"))
}
